import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
import { createServer } from 'node:http';
const port = 7791;
const hooks = [];
const hook = createServer((req, res) => { let b=''; req.on('data', c => b += c); req.on('end', () => { hooks.push(JSON.parse(b)); res.end('ok'); }); });
await new Promise((r) => hook.listen(7792, '127.0.0.1', r));
const transport = new StdioClientTransport({ command: 'node', args: ['dist/index.js'], env: { ...process.env, CCM_PORT: String(port), CCM_WEBHOOK_URL: 'http://127.0.0.1:7792/hook' } });
const client = new Client({ name: 'test', version: '0' }, { capabilities: {} });
const notes = [];
client.setNotificationHandler((await import('@modelcontextprotocol/sdk/types.js')).LoggingMessageNotificationSchema, (n) => notes.push(n.params));
await client.connect(transport);
await new Promise((r) => setTimeout(r, 500));
const base = `http://127.0.0.1:${port}`;
const post = await fetch(`${base}/messages`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ from: 'alice', text: 'hello agent' }) });
console.log('POST', post.status, await post.json());
const bad = await fetch(`${base}/messages`, { method: 'POST', body: '{"text":""}' });
console.log('POST invalid', bad.status, await bad.json());
await new Promise((r) => setTimeout(r, 300));
console.log('notifications received:', notes.length, JSON.stringify(notes[0]?.data));
const tool = await client.callTool({ name: 'read_messages', arguments: {} });
console.log('read_messages:', tool.content[0].text);
const again = await client.callTool({ name: 'read_messages', arguments: {} });
console.log('after drain:', again.content[0].text);
console.log('health:', await (await fetch(`${base}/health`)).text());
const sent = await client.callTool({ name: 'send_message', arguments: { text: 'agent reply' } });
console.log('send_message:', sent.isError ? 'ERROR' : 'ok', sent.content[0].text);
console.log('webhook received:', JSON.stringify(hooks[0]));
if (hooks[0]?.text !== 'agent reply' || sent.isError) process.exitCode = 1;
await client.close();
hook.close();
